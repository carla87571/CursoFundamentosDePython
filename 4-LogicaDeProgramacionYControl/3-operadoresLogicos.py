# Operadores de comparación

x = 5
y = 3
z = 5

# Igualdad
print(x == y)  # False

# Desigualdad
print(x != y)  # True

# Mayor que
print(x > y)   # True

# Menor que
print(x < y)   # False

# Mayor o igual que
print(x >= y)  # True

# Menor o igual que
print(x <= y)  # False


# Operadores lógicos (and, or, not)
print(x > y and x == z)  # True
print(x > y or x != z)   # True
print(not(x > y))        # False